def _status(start, end, today):
    """open / closed / upcoming / none"""
    if start is None and end is None:
        return "none"
    if end is not None and today > end:
        return "closed"
    if start is not None and today < start:
        return "upcoming"
    return "open"


def _days(a, b):
    return (b - a).days


def build_calendar(db_olympiads, today=None):
    """Собирает список карточек календаря: статические данные + сопоставление с БД.

    Для каждой олимпиады вычисляет статус регистрации и ближайший этап.
    Олимпиады из БД, не описанные здесь, добавляются в конец с их stages_list.
    """
    today = today or date.today()
    used_ids = set()
    cards = []

    for item in OLYMPIADS:
        db_match = None
        for o in db_olympiads or []:
            hay = ((o.slug or "") + " " + (o.name or "")).lower()
            if any(k in hay for k in item["match"]):
                db_match = o
                break
        if db_match is not None:
            used_ids.add(db_match.id)

        reg = item["registration"]
        reg_status = _status(reg["start"], reg["end"], today)
        reg_days_left = _days(today, reg["end"]) if reg["end"] and reg_status == "open" else None
        reg_days_until = _days(today, reg["start"]) if reg["start"] and reg_status == "upcoming" else None

        stages = []
        next_stage = None
        for s in item["stages"]:
            st = _status(s["start"], s["end"], today)
            s2 = dict(s)
            s2["status"] = st
            s2["days_until"] = _days(today, s["start"]) if st == "upcoming" else None
            if st in ("open", "upcoming") and next_stage is None:
                next_stage = s2
            stages.append(s2)

        cards.append({
            "key": item["key"],
            "slug": db_match.slug if db_match else None,
            "color": (db_match.color_hex if db_match and db_match.color_hex else item["color"]),
            "name": item["name"],
            "short": item["short"],
            "grades": item["grades"],
            "level": item["level"],
            "difficulty": item["difficulty"],
            "difficulty_label": DIFFICULTY_LABELS[item["difficulty"]],
            "difficulty_note": item["difficulty_note"],
            "about": item["about"],
            "format": item["format"],
            "registration": reg,
            "reg_status": reg_status,
            "reg_days_left": reg_days_left,
            "reg_days_until": reg_days_until,
            "stages": stages,
            "next_stage": next_stage,
            "sites": item["sites"],
            "steps": item["steps"],
            "mistakes": item["mistakes"],
            "gives": item["gives"],
            "docs": item["docs"],
            "tip": item["tip"],
            "static": True,
        })

    for o in db_olympiads or []:
        if o.id in used_ids:
            continue
        cards.append({
            "key": o.slug,
            "slug": o.slug,
            "color": o.color_hex or "#22d3a6",
            "name": o.name,
            "short": o.short_name,
            "grades": getattr(o, "grades_display", ""),
            "level": "",
            "difficulty": None,
            "difficulty_label": "",
            "difficulty_note": "",
            "about": o.description or "",
            "format": "",
            "registration": {"how": "", "start": None, "end": None, "text": "", "url": o.official_url or ""},
            "reg_status": "none",
            "reg_days_left": None,
            "reg_days_until": None,
            "stages": [
                {"name": (s.get("name") if isinstance(s, dict) else str(s)),
                 "text": (s.get("date_range", "") if isinstance(s, dict) else ""),
                 "status": "none", "exact": False, "days_until": None, "note": ""}
                for s in (getattr(o, "stages_list", None) or [])
            ],
            "next_stage": None,
            "sites": ([{"title": "Официальный сайт", "url": o.official_url}] if o.official_url else []),
            "steps": [], "mistakes": [], "gives": "", "docs": "", "tip": "",
            "static": False,
        })

    summary = {
        "open": [c for c in cards if c["reg_status"] == "open"],
        "upcoming": [c for c in cards if c["reg_status"] == "upcoming"],
        "closed": [c for c in cards if c["reg_status"] == "closed"],
        "none": [c for c in cards if c["reg_status"] == "none"],
    }
    return cards, summary, today
