def verify():
    all_ids = set()
    for g, ids in GRADE_THEMES.items():
        all_ids.update(ids)
    
    expected = set(THEMES.keys())
    missing = expected - all_ids
    extra = all_ids - expected
    
    print(f"Vsego unikalnyh tem v raspredelenii: {len(all_ids)}")
    print(f"Ozhidalos: {len(expected)}")
    
    if missing:
        print(f"** Ne vklyucheny v raspredelenie: {sorted(missing)}")
        for tid in sorted(missing):
            print(f"   {tid}: {THEMES[tid]['name']}")
    
    if extra:
        print(f"** Lishnie ID: {extra}")
    
    print(f"\nRaspredelenie po klassam:")
    total = 0
    for g in sorted(GRADE_THEMES.keys()):
        themes = GRADE_THEMES[g]
        subtopic_count = sum(len(THEMES[t]["subtopics"]) for t in themes)
        total += len(themes)
        names = [THEMES[t]["name"] for t in themes]
        print(f"\n  Klass {g}: {len(themes)} tem, {subtopic_count} podtem")
        for name in names:
            print(f"    * {name}")
    
    print(f"\nSumma po klassam (s uchetom dublication): {total}")
    print(f"Unikalnyh tem: {len(all_ids)}")
    
    # Proverka sovpadeniya s podtverzhdyonnymi counts
    expected_counts = {5: 3, 6: 4, 7: 13, 8: 17, 9: 20, 10: 20, 11: 16}
    ok = True
    for g, cnt in expected_counts.items():
        actual = len(GRADE_THEMES[g])
        if actual != cnt:
            print(f"** Klass {g}: ozhdalos {cnt} tem, polucheno {actual}")
            ok = False
    if ok:
        print("\n** Vse counts sovpadayut s podtverzhdyonnymi!")


def build_output():
    """Строит taxonomy_by_grade.json и grade_taxonomy_report.md"""
    
    # taxonomy_by_grade.json
    output = {
        "meta": {
            "total_themes": len(THEMES),
            "total_subtopics": sum(len(t["subtopics"]) for t in THEMES.values()),
            "grade_summary": {}
        },
        "grades": {}
    }
    
    for g in sorted(GRADE_THEMES.keys()):
        themes_in_grade = GRADE_THEMES[g]
        grade_entry = {
            "theme_count": len(themes_in_grade),
            "subtopic_count": sum(len(THEMES[t]["subtopics"]) for t in themes_in_grade),
            "themes": []
        }
        for tid in themes_in_grade:
            t = THEMES[tid]
            grade_entry["themes"].append({
                "id": tid,
                "name": t["name"],
                "subtopics": t["subtopics"]
            })
        output["grades"][str(g)] = grade_entry
        
        output["meta"]["grade_summary"][str(g)] = {
            "themes": len(themes_in_grade),
            "subtopics": sum(len(THEMES[t]["subtopics"]) for t in themes_in_grade)
        }
    
    output["meta"]["grade_summary"]["total_unique_themes"] = len(THEMES)
    output["meta"]["grade_summary"]["total_unique_subtopics"] = sum(len(t["subtopics"]) for t in THEMES.values())
    
    with open("taxonomy_by_grade.json", "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)
    
    print("\n** taxonomy_by_grade.json sozdan")
    
    # grade_taxonomy_report.md
    report = []
    report.append("# Распределение таксономии по классам\n")
    report.append("## Сводка\n")
    report.append("| Класс | Тем | Подтем |")
    report.append("|-------|-----|--------|")
    for g in sorted(GRADE_THEMES.keys()):
        themes = GRADE_THEMES[g]
        sub_count = sum(len(THEMES[t]["subtopics"]) for t in themes)
        report.append(f"| {g} | {len(themes)} | {sub_count} |")
    
    all_sub = sum(len(t["subtopics"]) for t in THEMES.values())
    report.append(f"| **Всего** | **{len(THEMES)}** | **{all_sub}** |\n")
    
    for g in sorted(GRADE_THEMES.keys()):
        themes = GRADE_THEMES[g]
        report.append(f"\n## {g} класс — {len(themes)} тем, {sum(len(THEMES[t]['subtopics']) for t in themes)} подтем\n")
        for tid in themes:
            t = THEMES[tid]
            report.append(f"### {t['name']} ({tid})")
            for st in t["subtopics"]:
                report.append(f"- {st}")
            report.append("")
    
    report_text = "\n".join(report)
    
    with open("grade_taxonomy_report.md", "w", encoding="utf-8") as f:
        f.write(report_text)
    
    print("** grade_taxonomy_report.md sozdan")


if __name__ == "__main__":
    verify()
    build_output()
