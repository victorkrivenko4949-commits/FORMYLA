#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Grade6_7Generator - Task Generator for Grades 6-7
Strict age restrictions: NO trigonometry, NO advanced geometry concepts.
"""

from typing import List
from .base_generator import TaskGenerator


class Grade6_7Generator(TaskGenerator):
    """
    Генератор задач для 6-7 классов.
    
    ЖЕСТКИЕ ИНВАРИАНТЫ:
    - Никакой тригонометрии (синус, косинус, тангенс)
    - Никаких логарифмов и сложных функций
    - Только базовая геометрия (периметр, площадь прямоугольника, сумма углов треугольника)
    - Строгий олимпиадный стиль: БЕЗ упоминания хакеров, киберспорта, видеоигр
    """
    
    def __init__(self, deepseek_client):
        super().__init__(deepseek_client, grade_range=(6, 7), max_retries=3)
    
    def get_allowed_concepts(self) -> List[str]:
        """Разрешенные концепции для 6-7 классов."""
        return [
            "базовая_арифметика",
            "простые_уравнения",
            "периметр_площадь_прямоугольника",
            "углы_треугольника_сумма_180",
            "пропорции",
            "проценты",
            "делимость",
            "НОД_НОК",
            "простые_числа",
            "остатки",
            "подсчет_вариантов_базовый",
            "логические_задачи",
            "скорость_время_расстояние"
        ]
    
    def get_forbidden_concepts(self) -> List[str]:
        """Запрещенные концепции для 6-7 классов."""
        return [
            "биссектриса",
            "медиана",
            "высота_треугольника",
            "синус",
            "косинус",
            "тангенс",
            "квадратные_уравнения",
            "теорема_пифагора",
            "подобие_треугольников",
            "вписанные_описанные_окружности",
            "логарифмы",
            "производные",
            "интегралы",
            "комплексные_числа",
            "тригонометрия"
        ]
    
    def _get_system_prompt(self) -> str:
        """Системный промпт с жесткими ограничениями для 6-7 классов."""
        return """Ты - профессиональный составитель олимпиадных задач для 6-7 классов.

КРИТИЧЕСКОЕ ТРЕБОВАНИЕ К ОФОРМЛЕНИЮ МАТЕМАТИКИ:
Абсолютно все переменные, числа, уравнения и формулы должны быть написаны СТРОГО в формате LaTeX и обернуты в \\( \\).
- **Индексы:** пиши \\(p_n\\), \\(q_i\\) (КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО писать слитно pn, qi).
- **Степени:** пиши \\(x^2\\), \\(p^2\\) (ЗАПРЕЩЕНО писать x^2 без обертки).
- **Дроби:** используй \\(\\frac{a}{b}\\) (ЗАПРЕЩЕНО использовать слэш a/b).
- **Корни:** используй \\(\\sqrt{x}\\) (ЗАПРЕЩЕНО писать sqrt(x)).
- **Умножение:** используй \\(\\cdot\\) вместо звездочки.
- Все математические символы внутри русского текста (даже одиночные переменные вроде \\(x\\)) должны быть в \\( \\)!
- НИКОГДА не используй одинарные доллары $ или двойные $$!

ДОПОЛНИТЕЛЬНЫЕ ТРЕБОВАНИЯ:
- СТРОГО ЗАПРЕЩЕНО: кавычки внутри текста.
- РЕШЕНИЕ: НЕ БОЛЕЕ 2 ПРЕДЛОЖЕНИЙ.
- ВЕРНИ СТРОГО ОДИН JSON-ОБЪЕКТ (без markdown).
- СТРОГО СОБЛЮДАЙ УКАЗАННЫЙ УРОВЕНЬ СЛОЖНОСТИ! Это не просто цифра, а конкретные требования к задаче.

ВОЗРАСТНЫЕ ОГРАНИЧЕНИЯ (6-7 КЛАСС):
ЗАПРЕЩЕНО: биссектриса, медиана, высота, синус, косинус, тангенс, квадратные уравнения, теорема Пифагора, подобие треугольников, вписанные/описанные окружности, логарифмы, производные, интегралы.

РАЗРЕШЕНО: базовая арифметика, простые уравнения, периметр, площадь прямоугольника, углы (сумма 180°), делимость, НОД/НОК, простые числа, остатки, базовый подсчет вариантов, логика, скорость-время-расстояние.

СТИЛЬ: Классический олимпиадный. БЕЗ приставок "В игре...", "В симуляторе...", "Хакер...", "В видеоигре...", "В киберспорте...".
Начинай сразу с сути: "Два автомобиля...", "Робот перемещается...", "На доске написаны...".

ФОРМАТ ОТВЕТА:
{
  "text": "Условие задачи (БЕЗ КАВЫЧЕК внутри текста)",
  "answer": "Краткий ответ (число, выражение или слово)",
  "solution": "Решение в 1-2 предложениях",
  "difficulty": 1-5,
  "topic": "название темы",
  "subtopic": "название подтемы",
  "options": ["вариант1", "вариант2", "вариант3"] // ТОЛЬКО для логических задач с 2-4 вариантами
}

ВАЖНО ПРО ОТВЕТЫ:
- Если задача математическая (алгебра, геометрия, теория чисел) — ответ ЧИСЛО или математическое выражение. Поле "options" НЕ добавляй.
- Если задача логическая (рыцари/лжецы, логика) с конечным числом вариантов (2-4 штуки) — добавь поле "options" с массивом вариантов. Правильный ответ ("answer") должен быть одним из элементов массива "options".
- Примеры для "options": ["рыцарь", "лжец"], ["да", "нет"], ["Петя", "Вася", "Коля"], ["красный", "синий", "зеленый"].
- КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО добавлять в условие инструкции по кодированию ответа (например, "введите 1, если рыцарь, 0, если лжец").
- Формулируй условие так, чтобы естественный ответ был кратким и однозначным."""
    
    def _build_prompt(self, topic: str, subtopic: str, difficulty: int, previous_tasks: List[str]) -> str:
        """Строит промпт для генерации задачи 6-7 класса."""
        
        # Получаем детальное описание уровня сложности
        difficulty_context = self.get_difficulty_context(difficulty)
        
        # Контекст предыдущих задач для уникальности
        previous_context = ""
        if previous_tasks:
            prev_str = "\n".join([f"{i+1}. {t[:100]}..." for i, t in enumerate(previous_tasks[-10:])])
            previous_context = f"""

КРИТИЧЕСКИ ВАЖНО: Ниже задачи, которые УЖЕ БЫЛИ. Твоя задача ДОЛЖНА КАРДИНАЛЬНО ОТЛИЧАТЬСЯ!
ЗАПРЕЩЕНО просто менять числа. Придумай СОВЕРШЕННО НОВУЮ задачу с другим сюжетом!

УЖЕ БЫЛИ:
{prev_str}
"""
        
        return f"""Сгенерируй ОДНУ олимпиадную задачу для 6-7 класса.

ТЕМА: {topic}
ПОДТЕМА: {subtopic}
СЛОЖНОСТЬ: {difficulty}
ВНИМАНИЕ НА СЛОЖНОСТЬ: {difficulty_context}
{previous_context}

ТРЕБОВАНИЯ:
1. Задача НЕ должна гуглиться (придумай оригинальный сюжет).
2. Ответ: число или краткое выражение (≤10 символов).
3. Решение: НЕ БОЛЕЕ 2 ПРЕДЛОЖЕНИЙ.
4. Используй ТОЛЬКО разрешенные концепции для 6-7 класса.
5. БЕЗ кавычек в тексте. Вместо прямой речи используй тире.
6. БЕЗ упоминания видеоигр, киберспорта, хакеров.

ВЕРНИ JSON:
{{
  "text": "Условие (БЕЗ КАВЫЧЕК)",
  "answer": "Ответ",
  "solution": "Решение (≤2 предложений)",
  "difficulty": {difficulty},
  "topic": "{topic}",
  "subtopic": "{subtopic}"
}}

БЕЗ markdown, БЕЗ текста вокруг JSON."""
