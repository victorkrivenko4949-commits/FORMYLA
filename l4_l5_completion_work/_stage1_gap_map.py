# Show field names once
keys = set()
for t in db:
    keys.update(t.keys())
print(f'Field names ({len(keys)}): {sorted(keys)}')

# Group by cell_key
cell_tasks = {}
for t in db:
    ck = t.get('cell_key', '')
    cell_tasks.setdefault(ck, []).append(t)

print(f'Unique cells with tasks in DB: {len(cell_tasks)}')

# ============================================================================
# 2. Build complete 258-cell gap map
# ============================================================================
TOTAL_CELLS = 258
TASKS_TARGET = TASKS_PER_CELL

rows = []
for grade, tids in GRADE_THEMES.items():
    for tid in tids:
        theme_data = THEMES[tid]
        theme_name = theme_data["name"]
        for si in range(3):  # 3 subtopics
            subtopic_name = theme_data["subtopics"][si]
            for level in [4, 5]:
                ck = build_cell_key(grade, level, tid, si)
                
                tasks = cell_tasks.get(ck, [])
                current_count = len(tasks)
                needed = TASKS_TARGET - current_count
                
                # Determine actual levels present
                actual_levels = set()
                for t in tasks:
                    lv = t.get('level', '?')
                    actual_levels.add(str(lv))
                levels_str = ','.join(sorted(actual_levels)) if actual_levels else f'L{level}'
                
                rows.append({
                    'cell_key': ck,
                    'grade': grade,
                    'level': level,
                    'theme_id': tid,
                    'theme_name': theme_name,
                    'subtopic_idx': si,
                    'subtopic': subtopic_name,
                    'current_count': current_count,
                    'needed': needed,
                    'current_levels': levels_str
                })

