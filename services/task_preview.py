# -*- coding: utf-8 -*-
r"""services/task_preview.py — безопасное усечение текста задачи для превью-карточек.

Раньше карточки резали текст задачи питоновским slice (`text[:100]`) или
Jinja-фильтром `truncate()` без учёта LaTeX-разметки. Из-за этого обрезка
могла:
  * пройти прямо посередине формулы `$...$` / `\(...\)`, оставляя открытый
    знак `$` без закрывающего — формула не рендерится, пользователь видит
    сырой фрагмент типа "$6";
  * разорвать слово или число посреди символов без всякого "...".

`preview_text()` сначала снимает LaTeX-обёртки (через normalize_condition),
затем режет по границе слова и всегда помечает обрезку через "…".
"""

from __future__ import annotations

from services.text_normalize import normalize_condition


def preview_text(text: str, limit: int = 160) -> str:
    """Вернуть безопасный для превью фрагмент условия задачи.

    - LaTeX убирается ДО обрезки, так что резать по формуле нечего.
    - Обрезка идёт по границе слова (никогда не рвёт слово/число).
    - Если текст обрезан — добавляется "…"; если нет — возвращается как есть.
    """
    if not text:
        return ""

    plain = normalize_condition(str(text))
    if len(plain) <= limit:
        return plain

    cut = plain[:limit]
    # Отступаем до последнего пробела, чтобы не разрезать слово/число.
    last_space = cut.rfind(" ")
    if last_space > 0:
        cut = cut[:last_space]

    return cut.rstrip(" ,.;:-") + "…"
