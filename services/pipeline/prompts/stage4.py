PREVIOUS_ERRORS_TEMPLATE = """## ВНИМАНИЕ: ПРЕДЫДУЩАЯ ПОПЫТКА ОТКЛОНЕНА

Формальный чекер нашёл в твоём прошлом ответе следующие ошибки KaTeX:

{errors_list}

Твой прошлый ответ был:

«{previous_output}»

Исправь ИМЕННО ЭТИ ошибки, не ломая остальное. Особенно обрати внимание на типичные паттерны выше.
"""


def build_previous_errors_block(errors: List[str],
                                previous_output: str) -> str:
    """Формирует блок с ошибками предыдущей попытки для промпта."""
    if not errors:
        return ""
    errors_list = "\n".join(f"- {e}" for e in errors)
    return PREVIOUS_ERRORS_TEMPLATE.format(
        errors_list=errors_list,
        previous_output=previous_output[:1000],
    )
